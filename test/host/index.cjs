const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const vscode = require('vscode');
exports.run = async function () {
  const extension = vscode.extensions.getExtension('neurologist.neurologist');
  assert.ok(extension,'Extension must be discoverable'); await extension.activate();
  const {openSource,applyDiagramRevision,DiagramProvider} = require(path.join(extension.extensionPath,'dist/extension.js'));
  const folder = vscode.workspace.workspaceFolders[0];
  await vscode.commands.executeCommand('vscode.openWith',vscode.Uri.joinPath(folder.uri,'example.neuro'),'neurologist.graph');
  assert.equal(vscode.window.tabGroups.activeTabGroup.activeTab.input.viewType,'neurologist.graph');
  const diagramGroup=vscode.window.tabGroups.activeTabGroup;
  const initialGroups=vscode.window.tabGroups.all.length;
  await openSource(folder,{kind:'definition',file:'model.py',symbol:'Encoder.forward'},diagramGroup.viewColumn);
  const codeGroup=vscode.window.tabGroups.activeTabGroup;
  assert.equal(vscode.window.tabGroups.all.length,initialGroups+1,'First source link should create exactly one split');
  assert.equal(vscode.window.activeTextEditor.document.fileName,path.join(folder.uri.fsPath,'model.py'));
  assert.equal(vscode.window.activeTextEditor.selection.start.line,4);
  await openSource(folder,{kind:'configuration',file:'config.yaml',symbol:'modules.encoder.hidden_size'},diagramGroup.viewColumn);
  assert.equal(vscode.window.tabGroups.activeTabGroup,codeGroup,'Subsequent links must reuse the code group even while it has focus');
  assert.equal(vscode.window.tabGroups.all.length,initialGroups+1,'Source navigation must not keep splitting');
  assert.equal(vscode.window.activeTextEditor.selection.start.line,4);
  await vscode.commands.executeCommand('vscode.openWith',vscode.Uri.joinPath(folder.uri,'example.neuro'),'neurologist.graph',diagramGroup.viewColumn);
  await vscode.commands.executeCommand('neurologist.openSource');
  assert.equal(vscode.window.tabGroups.activeTabGroup,codeGroup,'Edit YAML must share the code group');
  assert.equal(vscode.window.tabGroups.all.length,initialGroups+1);
  await vscode.window.tabGroups.close(codeGroup);
  await Promise.all([openSource(folder,{kind:'definition',file:'model.py',symbol:'Encoder.forward'},diagramGroup.viewColumn),openSource(folder,{kind:'configuration',file:'config.yaml',symbol:'modules.encoder.hidden_size'},diagramGroup.viewColumn)]);
  assert.equal(vscode.window.tabGroups.all.length,initialGroups+1,'Rapid clicks after closing the code group must create only one replacement split');
  await assert.rejects(openSource(folder,{kind:'definition',file:'../outside.py',symbol:'X'}),/Invalid source path/);
  await fs.symlink('/etc/hosts',path.join(folder.uri.fsPath,'outside-link'));
  await assert.rejects(openSource(folder,{kind:'definition',file:'outside-link',symbol:'X'}),/within the workspace/);
  const diagram = await vscode.workspace.openTextDocument(vscode.Uri.joinPath(folder.uri,'example.neuro'));
  await vscode.commands.executeCommand('vscode.openWith',diagram.uri,'default');
  await vscode.window.showTextDocument(diagram,{preserveFocus:false});
  const original = diagram.getText();
  const architecture = require('yaml').parse(original);
  architecture.title = 'Revised in conversation';
  const version = diagram.version;
  await applyDiagramRevision(diagram,architecture,version);
  assert.match(diagram.getText(),/Revised in conversation/);
  await assert.rejects(applyDiagramRevision(diagram,architecture,version),/diagram changed/);
  await vscode.window.showTextDocument(diagram,{preserveFocus:false});
  await new Promise(resolve=>setTimeout(resolve,250));
  await vscode.commands.executeCommand('workbench.action.focusActiveEditorGroup');
  const undone = new Promise((resolve,reject) => {const timer=setTimeout(() => {listener.dispose();reject(new Error('Undo did not restore the previous diagram'));},5000);const listener=vscode.workspace.onDidChangeTextDocument(event => {if (event.document.uri.toString()===diagram.uri.toString() && diagram.getText()===original) {clearTimeout(timer);listener.dispose();resolve();}});});
  await vscode.commands.executeCommand('undo');
  await undone;
  assert.equal(diagram.getText(),original,'Revisions must support normal VS Code Undo');
  const diagrams=new DiagramProvider();
  try {
    let entries=await diagrams.getChildren();
    assert.ok(entries.some(entry => entry.kind==='diagram' && entry.uri.path.endsWith('/example.neuro')));
    const generated=vscode.Uri.joinPath(folder.uri,'.neurologist','generated.neuro');
    await fs.mkdir(path.dirname(generated.fsPath),{recursive:true});
    const changed=new Promise((resolve,reject) => {const timer=setTimeout(() => {listener.dispose();reject(new Error('Diagram watcher did not refresh'));},5000);const listener=diagrams.onDidChangeTreeData(() => {clearTimeout(timer);listener.dispose();resolve();});});
    await fs.writeFile(generated.fsPath,original);await changed;
    entries=await diagrams.getChildren();
    const generatedEntry=entries.find(entry => entry.kind==='diagram' && entry.uri.toString()===generated.toString());
    assert.ok(generatedEntry,'Generated diagrams in a hidden output directory must be discoverable');
    const item=diagrams.getTreeItem(generatedEntry);
    await vscode.commands.executeCommand(item.command.command,...item.command.arguments);
    assert.equal(vscode.window.tabGroups.activeTabGroup.activeTab.input.viewType,'neurologist.graph');
    await vscode.commands.executeCommand('workbench.view.extension.neurologist');
    await vscode.commands.executeCommand('neurologist.analysis.focus');
    const deleted=new Promise((resolve,reject) => {const timer=setTimeout(() => {listener.dispose();reject(new Error('Diagram deletion did not refresh'));},5000);const listener=diagrams.onDidChangeTreeData(() => {clearTimeout(timer);listener.dispose();resolve();});});
    await fs.unlink(generated.fsPath);await deleted;
    assert.ok(!(await diagrams.getChildren()).some(entry => entry.kind==='diagram' && entry.uri.toString()===generated.toString()));
  } finally {diagrams.dispose();}
  const commands = await vscode.commands.getCommands();
  assert.ok(commands.includes('neurologist.analyze'));assert.ok(commands.includes('neurologist.regenerate'));
  const mock=vscode.Uri.joinPath(folder.uri,'mock-codex');
  const captured=vscode.Uri.joinPath(folder.uri,'captured-prompt.txt');
  const node=process.env.NEUROLOGIST_TEST_NODE;
  assert.ok(node,'The isolated test harness must supply its Node executable');
  await fs.writeFile(mock.fsPath,'#!'+node+'\n'+
    'const fs=require("node:fs");const args=process.argv.slice(2);let prompt="";process.stdin.on("data",chunk=>prompt+=chunk);process.stdin.on("end",()=>{fs.writeFileSync('+JSON.stringify(captured.fsPath)+',prompt);fs.writeFileSync(args[args.indexOf("--output-last-message")+1],JSON.stringify({architectures:[]}));});\n',{mode:0o755});
  await vscode.workspace.getConfiguration('neurologist').update('codexPath',mock.fsPath,vscode.ConfigurationTarget.Global);
  await vscode.commands.executeCommand('neurologist.analyze',{instructions:'sidebar analysis smoke marker',folder:folder.uri.toString(),start:true});
  let capturedPrompt='';
  const deadline=Date.now()+10000;
  while (Date.now()<deadline) {try {capturedPrompt=await fs.readFile(captured.fsPath,'utf8');break;}catch {await new Promise(resolve=>setTimeout(resolve,100));}}
  assert.match(capturedPrompt,/sidebar analysis smoke marker/,'Sidebar requests must reach Codex with their Instructions');
  await vscode.workspace.getConfiguration('neurologist').update('codexPath',undefined,vscode.ConfigurationTarget.Global);
  console.log('HOST SMOKE PASSED: custom editor, code navigation, HyperPyYAML navigation, path boundaries, undoable revisions, concurrent edit protection, analysis command, Activity Bar views, diagram discovery, watcher updates, diagram selection, sidebar-triggered analysis with Instructions, reusable code group, rapid links after group closure.');
};
